#!/usr/bin/env node
/**
 * Generate src/ui/flags.ts from country-flag-icons (devDependency, pinned to 1.6.20).
 *
 *   node scripts/gen-flags.mjs          write src/ui/flags.ts
 *   node scripts/gen-flags.mjs --check  fail if the committed file is stale
 *
 * SAD-355: every country row in Default country / the phone panel leads with its flag. The plugin
 * ships offline and the visual harness blocks every external request, so the SVGs are inlined
 * rather than fetched. An emoji flag would cost nothing but is not a flag on Windows (two
 * regional-indicator letters) or on Linux without Noto Color Emoji (tofu) — see
 * docs/decisions/country-flags.md.
 *
 * The country list is `libphonenumber-js`'s `getCountries()`, the SAME list the picker renders.
 * Iterating the library instead of the package's directory means the two can never disagree: a
 * region the parser supports always has a flag, and a future libphonenumber bump that adds one
 * the package lacks fails this check instead of rendering a blank row at runtime.
 *
 * Flags: MIT, © 2020 @catamphetamine — see LICENSE-FLAGS.
 */
import fs from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const require = createRequire(import.meta.url);
const FLAG_DIR = path.join(ROOT, 'node_modules/country-flag-icons/3x2');
const OUT = path.join(ROOT, 'src/ui/flags.ts');

const { getCountries } = require('libphonenumber-js/min');

/** Strip the XML prologue, comments and inter-tag whitespace; keep `viewBox` and the body. */
function split(svg) {
  const clean = svg
    .replace(/<\?xml[^>]*\?>/g, '')
    .replace(/<!--[\s\S]*?-->/g, '')
    .replace(/>\s+</g, '><')
    .replace(/\s+/g, ' ')
    .trim();
  const m = /^<svg[^>]*\sviewBox="([^"]+)"[^>]*>([\s\S]*)<\/svg>$/.exec(clean);
  if (!m) throw new Error(`unexpected SVG shape: ${clean.slice(0, 80)}`);
  return { box: m[1], body: m[2] };
}

function build() {
  const isos = getCountries();
  const rows = [];
  for (const iso of isos) {
    const file = path.join(FLAG_DIR, `${iso}.svg`);
    if (!fs.existsSync(file)) {
      throw new Error(
        `no flag asset for ${iso}. The country list comes from libphonenumber-js, so a region the ` +
          `parser supports must have a flag; bump country-flag-icons or add an override.`,
      );
    }
    const { box, body } = split(fs.readFileSync(file, 'utf8'));
    rows.push([iso, box, body]);
  }
  const entries = rows
    .map(([iso, box, body]) => `  ${iso}: { box: '${box}', body: '${body.replace(/'/g, "\\'")}' },`)
    .join('\n');

  return `// GENERATED by scripts/gen-flags.mjs — do not edit by hand.
//
// Country flags (SAD-355) for the ${rows.length} regions \`libphonenumber-js\` supports, inlined
// because the plugin ships offline. Source: country-flag-icons 1.6.20, MIT, © 2020
// @catamphetamine (https://gitlab.com/catamphetamine/country-flag-icons); attribution in
// LICENSE-FLAGS and README. The monogram in \`CountryList\` stays as the fallback for a code with
// no entry here — none at the pinned versions, and \`--check\` keeps it that way.

/** \`box\` is the viewBox, \`body\` the SVG's inner markup. Both are static asset data. */
const FLAGS: Record<string, { box: string; body: string }> = {
${entries}
};

/**
 * The flag for an ISO 3166-1 alpha-2 code as inline SVG, or '' when there is no asset (the caller
 * falls back to the two-letter monogram). \`aria-hidden\` and \`focusable="false"\`: the row's
 * accessible name stays the country name, which is right beside the flag.
 */
export function flagIcon(iso: string): string {
  const f = FLAGS[iso];
  if (!f) return '';
  return \`<svg class="tablify__country-flag-svg" viewBox="\${f.box}" aria-hidden="true" focusable="false">\${f.body}</svg>\`;
}

/** Whether a flag exists — lets a caller choose the monogram without parsing the markup. */
export function hasFlag(iso: string): boolean {
  return FLAGS[iso] !== undefined;
}
`;
}

const next = build();
const prev = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : null;

if (process.argv.includes('--check')) {
  if (prev !== next) {
    console.error('FAIL: src/ui/flags.ts is stale. Run `node scripts/gen-flags.mjs`.');
    process.exit(1);
  }
  console.log('Flag check PASS');
  process.exit(0);
}

fs.writeFileSync(OUT, next);
console.log(`Wrote ${path.relative(ROOT, OUT)} (${(next.length / 1024).toFixed(0)} KB)`);
