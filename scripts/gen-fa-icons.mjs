#!/usr/bin/env node
/**
 * Generate src/ui/faIcons.ts from @fortawesome/fontawesome-free (devDependency, pinned to the
 * 6.4.0 release the prototype loads from its CDN). The plugin ships offline, so the prototype's
 * glyphs are inlined as SVG path data. Icons: CC BY 4.0, © Fonticons, Inc. — see LICENSE-FONTS.
 *
 *   node scripts/gen-fa-icons.mjs          write src/ui/faIcons.ts
 *   node scripts/gen-fa-icons.mjs --check  fail if the committed file is stale
 *
 * To add a glyph, append its FA name (solid set) — or `{ set: 'regular', name }` for a regular-set
 * glyph — to GLYPHS and re-run.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const FA = path.join(ROOT, 'node_modules/@fortawesome/fontawesome-free');
const OUT = path.join(ROOT, 'src/ui/faIcons.ts');

/** Glyph names used by the plugin UI, in the order they first appear. Strings are solid-set. */
const GLYPHS = [
  // title row (SAD-77)
  'file-import',
  'file-export',
  'file-csv',
  'copy',
  // toolbar (SAD-78)
  'magnifying-glass',
  'cloud-arrow-up',
  'rotate-left',
  'rotate-right',
  'filter',
  'plus',
  'table-columns',
  'sliders',
  // filter builder (SAD-78)
  'xmark',
  'trash-can',
  // grid header capsule (SAD-79)
  'grip-vertical',
  'key',
  'ellipsis-vertical',
  // field-type badges (SAD-79), prototype FT[type].icon
  'font',
  'align-left',
  'hashtag',
  'dollar-sign',
  'percent',
  'stopwatch',
  'star',
  'square-check',
  'calendar',
  'clock',
  'link',
  'envelope',
  'phone',
  'circle-dot',
  'list-check',
  'paperclip',
  'square-root-variable',
  'diagram-project',
  'arrow-down-1-9',
  'calendar-plus',
  'calendar-check',
  // Options panel and group headers (SAD-81)
  'filter-circle-xmark',
  'chevron-down',
  'chevron-right',
  // Date & time panel (COD-75): month stepper arrow (chevron-right was already inlined)
  'chevron-left',
  // Select panel, option manager, attachment panel (SAD-90, the prototype's own glyphs:
  // fa-check on a picked row, fa-palette in the panel footer and the manager title,
  // fa-arrow-up / fa-arrow-down on the per-option reorder buttons)
  'check',
  'palette',
  'arrow-up',
  'arrow-down',
  // COD-71: the unchecked checkbox cell. The prototype draws `fa-regular fa-square`, so this is
  // the one glyph from the regular set (solid `square` is a filled box and reads as checked).
  { set: 'regular', name: 'square' },
];

/** A GLYPHS entry as { set, name }; a bare string is solid-set. */
function glyphSpec(entry) {
  return typeof entry === 'string' ? { set: 'solid', name: entry } : entry;
}

function build() {
  const pkg = JSON.parse(fs.readFileSync(path.join(FA, 'package.json'), 'utf8'));
  if (pkg.version !== '6.4.0') throw new Error(`expected @fortawesome/fontawesome-free 6.4.0, found ${pkg.version}`);
  const entries = GLYPHS.map(glyphSpec).map(({ set, name }) => {
    const svg = fs.readFileSync(path.join(FA, 'svgs', set, `${name}.svg`), 'utf8');
    const viewBox = /viewBox="([^"]+)"/.exec(svg)?.[1];
    const d = /<path d="([^"]+)"/.exec(svg)?.[1];
    if (!viewBox || !d) throw new Error(`cannot read ${name}.svg`);
    const width = Number(viewBox.split(/\s+/)[2]);
    return `  '${name}': { w: ${width}, d: '${d}' },`;
  });
  return `// GENERATED by scripts/gen-fa-icons.mjs — do not edit by hand.
//
// Font Awesome Free ${pkg.version} solid glyphs (plus the one regular-set glyph the prototype's
// unchecked checkbox uses), the exact set the prototype loads from its CDN, inlined because the
// plugin ships offline. Icons © Fonticons, Inc., licensed CC BY 4.0
// (https://fontawesome.com/license/free); attribution in LICENSE-FONTS and README.

/** Glyph path data: \`w\` is the viewBox width (height is always 512). */
const GLYPHS = {
${entries.join('\n')}
} as const;

export type FaGlyph = keyof typeof GLYPHS;

/**
 * Inline SVG markup for a glyph, sized like Font Awesome's own inline SVGs (svg-inline--fa):
 * 1em tall, width from the viewBox, \`currentColor\` fill. The \`tablify__fa\` class carries the
 * shared metrics in styles.css; size it with font-size on the container.
 *
 * Pass \`sizePx\` (the font-size the container renders this glyph at) to take Font Awesome's own
 * box width: the webfont rounds an icon's advance to the nearest whole pixel — measured
 * \`cloud-arrow-up\` 640/512 × 11px = 13.75 → 14, \`plus\` 448/512 × 10px = 8.75 → 9, \`grip-vertical\`
 * 320/512 × 12px = 7.5 → 8. An SVG keeps the exact fraction (SAD-86's \`hc-grip\` needed a manual
 * 0.725px nudge for the same reason), and a quarter-pixel is enough to shift every glyph after an
 * icon-only pill and turn the whole toolbar row fuzzy against the prototype (SAD-92).
 */
export function faIcon(name: FaGlyph, sizePx?: number): string {
  const g = GLYPHS[name];
  // With a size, emit whole pixels: an \`em\` width that lands a hair under the target (14/11em × 11px
  // = 13.9997) is snapped down to the next 1/64px by layout and the quarter-pixel comes back.
  const box = sizePx
    ? { width: \`\${Math.round((g.w / 512) * sizePx)}\`, height: \`\${sizePx}\` }
    : { width: \`\${(g.w / 512).toFixed(4)}em\`, height: '1em' };
  return \`<svg class="tablify__fa" viewBox="0 0 \${g.w} 512" width="\${box.width}" height="\${box.height}" fill="currentColor" aria-hidden="true" focusable="false"><path d="\${g.d}"></path></svg>\`;
}
`;
}

const text = build();
if (process.argv.includes('--check')) {
  const current = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
  if (current !== text) {
    console.error('src/ui/faIcons.ts is stale: run node scripts/gen-fa-icons.mjs');
    process.exit(1);
  }
  console.log('FA icon check PASS');
} else {
  fs.writeFileSync(OUT, text);
  console.log(`wrote ${path.relative(ROOT, OUT)} (${GLYPHS.length} glyphs)`);
}
